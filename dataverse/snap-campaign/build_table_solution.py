def build(template_zip, out):
    src = zipfile.ZipFile(template_zip)
    c = src.read("customizations.xml").decode("utf-8-sig")
    start = c.index(f">{TEMPLATE_SCHEMA}</Name>")
    ent = c[c.rindex("<Entity>", 0, start):c.index("</Entity>", start) + len("</Entity>")]
    t = attr_blocks(ent)
    multi = re.search(r'<attribute PhysicalName="[^"]+">\s*<Type>multiselectpicklist</Type>.*?</attribute>',
                      c, re.S).group(0)

    # System columns (owner, created/modified, currency, state...) carried over from the template.
    system = [b for n, b in t.items() if not n.startswith("sanidi_")]
    pk = rename(t[f"{TEMPLATE_SCHEMA}Id"], f"{TEMPLATE_SCHEMA}Id", f"{SCHEMA}Id") \
        .replace(f"<Name>{SCHEMA}Id</Name>", f"<Name>{LOGICAL}id</Name>") \
        .replace(f"<LogicalName>{SCHEMA}Id</LogicalName>", f"<LogicalName>{LOGICAL}id</LogicalName>")
    pk = re.sub(r"<displaynames>.*?</displaynames>",
                f'<displaynames>\n                <displayname description="{DISPLAY}" languagecode="1033" />\n'
                f"              </displaynames>", pk, count=1, flags=re.S)
    custom = [b for f in FIELDS for b in build_attribute(t, f, multi)]
    attributes = "<attributes>\n            " + "\n            ".join(system + [pk] + custom) + \
                 "\n          </attributes>"

    head = ent[:ent.index("<attributes>")]
    head = re.sub(r"<LocalizedNames>.*?</Descriptions>",
                  f'<LocalizedNames>\n            <LocalizedName description="{DISPLAY}" languagecode="1033" />\n'
                  f'          </LocalizedNames>\n          <LocalizedCollectionNames>\n'
                  f'            <LocalizedCollectionName description="{PLURAL}" languagecode="1033" />\n'
                  f'          </LocalizedCollectionNames>\n          <Descriptions>\n'
                  f'            <Description description="{escape(DESCRIPTION)}" languagecode="1033" />\n'
                  f"          </Descriptions>", head, count=1, flags=re.S)
    info_tail = ent[ent.index("</attributes>") + len("</attributes>"):ent.index("</EntityInfo>")]
    info_tail = re.sub(r"\s*<EntityKeys>.*?</EntityKeys>", "", info_tail, flags=re.S)
    info_tail = set_tag(info_tail, "EntitySetName", f"{LOGICAL}s")
    ribbon = re.search(r"<RibbonDiffXml>.*?</RibbonDiffXml>", ent, re.S).group(0)
    entity = (head + attributes + "\n          " + entity_key() + info_tail.lstrip() + "</EntityInfo>\n      "
              + form_xml() + "\n      " + saved_queries(ent) + "\n      " + ribbon + "\n    </Entity>")
    entity = entity.replace(TEMPLATE_SCHEMA, SCHEMA).replace(TEMPLATE_LOGICAL, LOGICAL) \
                   .replace("Meta Campaigns", PLURAL).replace("Meta Campaign", DISPLAY)

    rel_names = [f"business_unit_{TEMPLATE_LOGICAL}", f"lk_{TEMPLATE_LOGICAL}_createdby",
                 f"lk_{TEMPLATE_LOGICAL}_modifiedby", f"owner_{TEMPLATE_LOGICAL}", f"team_{TEMPLATE_LOGICAL}",
                 f"TransactionCurrency_{TEMPLATE_SCHEMA}", f"user_{TEMPLATE_LOGICAL}"]
    rels = [re.search(rf'<EntityRelationship Name="{n}">.*?</EntityRelationship>', c, re.S).group(0)
            .replace(TEMPLATE_SCHEMA, SCHEMA).replace(TEMPLATE_LOGICAL, LOGICAL) for n in rel_names]

    optionset = f"""<optionset Name="{DELIVERY_OPTIONSET}" localizedName="Snap Campaign Delivery Status">
      <OptionSetType>picklist</OptionSetType>
      <IsGlobal>1</IsGlobal>
      <IntroducedVersion>1.0.0</IntroducedVersion>
      <IsCustomizable>1</IsCustomizable>
      <ExternalTypeName></ExternalTypeName>
      <displaynames>
        <displayname description="Snap Campaign Delivery Status" languagecode="1033" />
      </displaynames>
      <Descriptions>
        <Description description="Snapchat campaign delivery_status values" languagecode="1033" />
      </Descriptions>
      <options>
{option_xml(DELIVERY_STATUS, 8)}
      </options>
    </optionset>"""

    root_open = re.match(r".*?<ImportExportXml[^>]*>", c, re.S).group(0)
    customizations = (f"{root_open}\n  <Entities>\n    {entity}\n  </Entities>\n  <Roles />\n  <Workflows />\n"
                      f"  <FieldSecurityProfiles />\n  <Templates />\n  <EntityMaps />\n  <EntityRelationships>\n    "
                      + "\n    ".join(rels) + "\n  </EntityRelationships>\n  <OrganizationSettings />\n"
                      f"  <optionsets>\n    {optionset}\n  </optionsets>\n  <CustomControls />\n"
                      f"  <EntityDataProviders />\n  <Languages>\n    <Language>1033</Language>\n  </Languages>\n"
                      f"</ImportExportXml>\n")

    solution = src.read("solution.xml").decode("utf-8-sig")
    solution = re.sub(r"<RootComponents>.*?</RootComponents>",
                      f'<RootComponents>\n      <RootComponent type="1" schemaName="{LOGICAL}" behavior="0" />\n'
                      f'      <RootComponent type="9" schemaName="{DELIVERY_OPTIONSET}" behavior="0" />\n'
                      f"    </RootComponents>", solution, count=1, flags=re.S)
    solution = re.sub(r"<MissingDependencies>.*?</MissingDependencies>", "<MissingDependencies />",
                      solution, count=1, flags=re.S)

    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("[Content_Types].xml", src.read("[Content_Types].xml"))
        z.writestr("solution.xml", solution)
        z.writestr("customizations.xml", customizations)
    print(f"Wrote {out}: {len(FIELDS)} columns, {len(rels)} system relationships")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--template", required=True, help="Exported AlSanidiMarketing solution zip")
    ap.add_argument("--out", default="SnapCampaignTable.zip")
    a = ap.parse_args()
    build(a.template, a.out)
