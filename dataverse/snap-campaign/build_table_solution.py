"""Builds an unmanaged solution package that creates the "Snap Campaign" table
(sanidi_SnapCampaign) in the "AlSanidi | Marketing" solution, with its columns,
choices, alternate key, main form and views.

The Dataverse XML format is taken from the existing Meta Campaign table
(sanidi_MetaCampaign) in an export of the solution, so the new table matches its
conventions. Field definitions come from
https://developers.snap.com/marketing-api/Ads-API/campaigns.

Run:
  pac solution export --name AlSanidiMarketing --path AlSanidiMarketing.zip --environment <env>
  python3 build_table_solution.py --template AlSanidiMarketing.zip [--out SnapCampaignTable.zip]
  pac solution import --path SnapCampaignTable.zip --environment <env>

The package contains only the new table and its delivery-status option set, so
importing it leaves the rest of the solution untouched. IDs are deterministic, so
re-importing updates the same table, form and views.
"""
